    initFbaSelect2($(document));

    $('#fba-auto-table').DataTable({
        processing: true,
        serverSide: true,
        ajax: '{{ route('admin.fba-auto.ajax') }}',
        columns: [
            {data: 'DT_RowIndex', name: 'DT_RowIndex', orderable: false, searchable: false},
            {data: 'shipment_id', name: 'shipment_id'},
            {data: 'shipment_date', name: 'shipment_date'},
            {data: 'product_name', name: 'product_name'},
            {data: 'qty', name: 'qty'},
            {data: 'state', name: 'state'},
            {data: 'warehouse_name', name: 'warehouse_name'},
            {data: 'qty_price', name: 'qty_price'},
            {data: 'generated_by', name: 'generated_by', orderable: false, searchable: false},
            {data: 'generated_at', name: 'created_at'},
            {data: 'updated_by', name: 'updated_by', orderable: false, searchable: false},
            {data: 'updated_at', name: 'updated_at'},
            {data: 'status', name: 'status', orderable: false, searchable: false},
            {data: 'action', name: 'action', orderable: false, searchable: false},
        ],
        order: [[1, 'desc']]
    });
});

function initFbaSelect2($scope) {
    $scope.find('.fba-select2').each(function() {
        const $select = $(this);
        const $modal = $select.closest('.modal');

        if ($select.hasClass('select2-hidden-accessible')) {
            $select.select2('destroy');
        }

        $select.select2({
            width: '100%',
            tags: $select.data('tags') === true || $select.data('tags') === 1,
            placeholder: $select.data('placeholder') || 'Select option',
            allowClear: true,
            dropdownParent: $modal.length ? $modal : $(document.body)
        });
    });
}

$(document).on('click', '.edit-btn', function() {
    let id = $(this).data('id');
    $.ajax({
        url: `/admin/fba-auto/edit/${id}`,
        type: 'GET',
        success: function(response) {
            $('#edit-content').html(response);
            initFbaSelect2($('#editModal'));
            // Init product select2 on existing rows
            $('#editModal .edit-product-select2').each(function() {
                initProductSelect2($(this), $('#editModal'));
            });
            // Counter starts after existing rows so new row indices don't clash
            editProductRowIndex = $('#edit-product-rows tr').length;
            $('#editModal').modal('show');
        },
        error: function() {
            toastr.error('Failed to load data');
        }
    });
});

$(document).on('click', '.delete-btn', function() {
    let id = $(this).data('id');
    Swal.fire({
        title: 'Are you sure?',
        text: 'This action cannot be undone!',
        icon: 'warning',
        showCancelButton: true,
        confirmButtonColor: '#dc3545',
        cancelButtonColor: '#6c757d',
        confirmButtonText: 'Yes, Delete!'
    }).then((result) => {
        if (result.isConfirmed) {
            $.ajax({
                url: `/admin/fba-auto/delete/${id}`,
                type: 'DELETE',
                headers: {'X-CSRF-TOKEN': $('meta[name="csrf-token"]').attr('content')},
                success: function(response) {
                    if (response.success) {
                        toastr.success('Deleted successfully');
                        $('#fba-auto-table').DataTable().ajax.reload();
                    } else {
                        toastr.error(response.message);
                    }
                }
            });
        }
    });
});

$(document).on('click', '#add-product-row', function() {
    addProductRow();
});

$(document).on('click', '.remove-row-btn', function() {
    if ($('#product-rows tr').length === 1) {
        toastr.warning('At least one product row is required');
        return;
    }
    $(this).closest('tr').remove();
    updateRowNumbers();
});

$('#create-form').on('submit', function(e) {
    e.preventDefault();
    let formData = new FormData(this);

    $.ajax({
        url: '{{ route('admin.fba-auto.store') }}',
        type: 'POST',
        data: formData,
        processData: false,
        contentType: false,
        headers: {'X-CSRF-TOKEN': $('meta[name="csrf-token"]').attr('content')},
        success: function(response) {
            if (response.success) {
                toastr.success(response.message);
                $('#createModal').modal('hide');
                $('#fba-auto-table').DataTable().ajax.reload();
            } else {
                toastr.error(response.message);
            }
        },
        error: function(xhr) {
            let msg = xhr.responseJSON?.message || 'Error occurred';
            let errors = xhr.responseJSON?.errors;
            if (errors) {
                msg = Object.values(errors).flat().join('<br>');
            }
            toastr.error(msg);
        }
    });
});

$(document).on('click', '#add-edit-product-row', function() {
    addEditProductRow();
});

$(document).on('click', '.remove-edit-row-btn', function() {
    if ($('#edit-product-rows tr').length === 1) {
        toastr.warning('At least one product row is required');
        return;
    }
    $(this).closest('tr').remove();
