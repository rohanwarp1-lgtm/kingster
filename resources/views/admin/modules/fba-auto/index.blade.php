$('#createModal').on('hidden.bs.modal', function() {
    $('#create-form')[0].reset();
    $('#create-form .fba-select2').val(null).trigger('change');
    $('#product-rows').empty();
    productRowIndex = 0;
});

$('#editModal').on('hidden.bs.modal', function() {
    const form = $(this).find('form')[0];
    if (form) form.reset();
    $(this).find('.fba-select2').val(null).trigger('change');
});
